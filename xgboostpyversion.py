# ============================================================
# Train the final deployable Gardner/P-NP model: XGBoost, 25 trees,
# max_depth=4, top-8 clinical features -- for the Chinese 2542-patient
# day-3 embryo dataset.
#
# Run this on your own machine to have your own reproducible result.
# Set XLSX_PATH below to wherever "Embryo dataset_2542.xlsx" is.

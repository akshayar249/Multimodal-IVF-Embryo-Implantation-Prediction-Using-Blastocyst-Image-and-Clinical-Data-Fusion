import openpyxl
import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.metrics import roc_auc_score, average_precision_score, accuracy_score
from xgboost import XGBClassifier

XLSX_PATH = '/content/Embryo_Dataset_extracted/Embryo dataset/Embryo dataset_2542.xlsx'   # <-- set this to your actual file path
MODEL_OUT_PATH = 'gardner_pnp_model.json'

# Column order exactly as they appear in the spreadsheet
COL_NAMES = ['Image', 'label', 'age', 'FSH', 'PRL', 'T', 'P', 'AMH',
             'WBC', 'platelets', 'hematocrit', 'PT', 'APTT', 'TT', 'Ddimer',
             'TPO', 'glucose', 'uric_acid',
             'm_conc', 'm_morph_pct', 'm_PR', 'm_NP', 'm_survival', 'm_DFI',
             'm_ALT', 'm_AST', 'm_creatinine', 'm_WBC', 'm_platelets', 'm_glucose',
             'Gn_days', 'HCG_day_P', 'm_proc_NP', 'm_proc_method', 'm_proc_density',
             'm_proc_PR', 'm_proc_IM', 'n_frozen']

# Top-8 features by importance (from the full 35-feature model) -- the
# hardware-realistic feature set locked in for FPGA deployment.
TOP8_FEATS = ['glucose', 'm_proc_IM', 'n_frozen', 'P', 'm_proc_density', 'age',
              'm_proc_method', 'm_proc_NP']

N_TREES = 25
MAX_DEPTH = 4
LEARNING_RATE = 0.05

# ------------------------------------------------------------
# 1. Load
# ------------------------------------------------------------
wb = openpyxl.load_workbook(XLSX_PATH, data_only=True)
ws = wb['2542']
rows = list(ws.iter_rows(min_row=2, values_only=True))
clin = pd.DataFrame(rows, columns=COL_NAMES)
clin['patient'] = clin['Image'].astype(str).str.split('_').str[0]

print(f"Loaded {clin.shape[0]} rows, {clin['patient'].nunique()} unique patients")
print(f"Label balance: {clin['label'].value_counts().to_dict()}")

X = SimpleImputer(strategy='median').fit_transform(clin[TOP8_FEATS])
y = clin['label'].values
groups = clin['patient'].values

# ------------------------------------------------------------
# 2. Honest evaluation FIRST -- patient-grouped CV, so a patient's
#    multiple embryo rows (which share identical clinical values and
#    the same outcome label) can never be split across train and test.
#    A plain row-level split leaks and inflates the score badly here --
#    confirmed this the hard way earlier, worth keeping this comment
#    as a reminder not to "simplify" this back to a plain KFold.
# ------------------------------------------------------------
print("\nRunning patient-grouped cross-validation (20 repeats x 5 folds)...")
aucs, praucs, accs = [], [], []
for repeat in range(20):
    sgkf = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=repeat)
    for tr, te in sgkf.split(X, y, groups):
        assert set(groups[tr]).isdisjoint(set(groups[te])), "patient leakage across folds!"
        Xtr, Xte, ytr, yte = X[tr], X[te], y[tr], y[te]
        n_pos, n_neg = (ytr == 1).sum(), (ytr == 0).sum()
        clf = XGBClassifier(n_estimators=N_TREES, max_depth=MAX_DEPTH,
                             learning_rate=LEARNING_RATE,
                             scale_pos_weight=n_neg / max(n_pos, 1),
                             eval_metric='logloss', random_state=0, verbosity=0)
        clf.fit(Xtr, ytr)
        proba = clf.predict_proba(Xte)[:, 1]
        aucs.append(roc_auc_score(yte, proba))
        praucs.append(average_precision_score(yte, proba))
        accs.append(accuracy_score(yte, clf.predict(Xte)))

aucs, praucs, accs = np.array(aucs), np.array(praucs), np.array(accs)
lo, hi = np.percentile(aucs, [2.5, 97.5])
print(f"\nPatient-grouped CV AUC:  mean={aucs.mean():.3f}  95% CI=[{lo:.3f},{hi:.3f}]  (n={len(aucs)})")
lo, hi = np.percentile(praucs, [2.5, 97.5])
print(f"Patient-grouped CV PRAUC: mean={praucs.mean():.3f}  95% CI=[{lo:.3f},{hi:.3f}]")
print(f"Patient-grouped CV Accuracy: mean={accs.mean():.3f}")

# ------------------------------------------------------------
# 3. Fit the FINAL model on all data -- this is the one that gets
#    deployed, so it should use every patient available, not a
#    held-out split (the CV above already told us how well it
#    generalizes; this step just gives it the most data possible)
# ------------------------------------------------------------
n_pos, n_neg = (y == 1).sum(), (y == 0).sum()
final_model = XGBClassifier(n_estimators=N_TREES, max_depth=MAX_DEPTH,
                             learning_rate=LEARNING_RATE,
                             scale_pos_weight=n_neg / max(n_pos, 1),
                             eval_metric='logloss', random_state=0, verbosity=0)
final_model.fit(X, y)

final_model.save_model(MODEL_OUT_PATH)
print(f"\nSaved final model: {MODEL_OUT_PATH}")
print("This is the file to download and bring back for the Verilog conversion step.")

# feature importances, for reference in your writeup
importances = pd.Series(final_model.feature_importances_, index=TOP8_FEATS).sort_values(ascending=False)
print("\nFeature importances (final model):")
print(importances.round(3))